# -*- coding: utf-8 -*-
"""Validate / calibrate the supplementary detection layer on YOUR labelled texts.

Usage:   python eval_signals.py DATA_DIR

    DATA_DIR/human/*.txt   texts written by people      (UTF-8)
    DATA_DIR/ai/*.txt      texts generated by AI         (UTF-8)

Reports, for every signal and for the whole layer:
  AUC   0.5 = no better than chance, 1.0 = perfect separation.
  FPR   share of HUMAN texts wrongly pushed above a cut-off (false accusations).

How to act on it (edit ai_signals.py):
  * signal AUC close to 0.5   -> lower its weight (or drop it);
  * signal AUC below 0.5      -> it points the wrong way on your data; flip or move its anchors;
  * layer FPR too high        -> raise the cut-offs in layer_label()/fuse() or lower LAYER_MAX_WEIGHT.
Use at least 30 texts per class, of the same kind (genre, length, language) you will really check,
and include human writing by non-native speakers and formal human writing: those are the hard cases.
"""
import pathlib
import re
import sys
from collections import defaultdict

import ai_signals as S


def load(folder: pathlib.Path):
    out = []
    for f in sorted(folder.glob("*.txt")):
        text = f.read_text(encoding="utf-8", errors="ignore")
        paras = [p for p in re.split(r"\n\s*\n", text) if p.strip()]
        if paras:
            out.append(paras)
    return out


def auc(pos, neg):
    if not pos or not neg:
        return None
    wins = sum(1.0 if p > n else 0.5 if p == n else 0.0 for p in pos for n in neg)
    return wins / (len(pos) * len(neg))


def main(root: str):
    root = pathlib.Path(root)
    data = {"ai": load(root / "ai"), "human": load(root / "human")}
    print(f"texts: ai={len(data['ai'])}  human={len(data['human'])}")
    if min(len(v) for v in data.values()) < 30:
        print("WARNING: fewer than 30 texts in a class; AUC values are unreliable.\n")

    zs = {"ai": defaultdict(list), "human": defaultdict(list)}
    scores = {"ai": [], "human": []}
    for label, texts in data.items():
        for paras in texts:
            L = S.analyze(paras)
            if not L.sufficient:
                continue
            scores[label].append(L.score)
            for s in L.signals:
                if s.z is not None:
                    zs[label][s.key].append(s.z)

    print(f"\n{'signal':14s} {'n(ai)':>6s} {'n(hu)':>6s} {'AUC':>6s} {'mean z ai':>10s} {'mean z human':>13s}")
    for key in sorted(set(zs["ai"]) | set(zs["human"])):
        a, h = zs["ai"][key], zs["human"][key]
        v = auc(a, h)
        ma = sum(a) / len(a) if a else float("nan")
        mh = sum(h) / len(h) if h else float("nan")
        print(f"{key:14s} {len(a):6d} {len(h):6d} {'n/a' if v is None else f'{v:.3f}':>6s} {ma:10.2f} {mh:13.2f}")

    v = auc(scores["ai"], scores["human"])
    print(f"\nLAYER AUC = {'n/a' if v is None else f'{v:.3f}'}")
    if scores["ai"] and scores["human"]:
        print(f"\n{'cut-off':>8s} {'TPR (ai caught)':>16s} {'FPR (human flagged)':>20s}")
        for t in (44, 50, 56, 62, 68, 75):
            tpr = sum(x >= t for x in scores["ai"]) / len(scores["ai"])
            fpr = sum(x >= t for x in scores["human"]) / len(scores["human"])
            print(f"{t:8d} {tpr:16.2%} {fpr:20.2%}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
