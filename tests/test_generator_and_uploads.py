def _with_core(data, creator="", created="2026-03-01T10:00:00Z", description=""):
    core = ('<?xml version="1.0" encoding="UTF-8"?><cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" '
            'xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" '
            'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"><dc:creator>%s</dc:creator><dc:description>%s</dc:description>'
            '<dcterms:created xsi:type="dcterms:W3CDTF">%s</dcterms:created><dcterms:modified xsi:type="dcterms:W3CDTF">%s</dcterms:modified>'
            '</cp:coreProperties>' % (creator, description, created, created))
    out = io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(data)) as zi, zipfile.ZipFile(out, "w") as zo:
        for n in zi.namelist():
            zo.writestr(n, zi.read(n))
        zo.writestr("docProps/core.xml", core)
    return out.getvalue()


def _gen(report):
    return report.features.get("meta_gen", (0, 0, 0))[2]


def test_explicit_generator_counts_when_the_wording_agrees():
    plain = b.analyze_uploaded_bytes("a.docx", _docx([LLM_PARA] * 30))
    gen = b.analyze_uploaded_bytes("b.docx", _with_core(_docx([LLM_PARA] * 30), "python-docx", "2013-12-23T23:15:00Z", "generated by python-docx"))
    assert _gen(gen) > b.META_GEN_MAX + 0.5
    assert gen.score >= plain.score - 0.5
    assert any("بصمة المولّد الصريحة" in x for x in gen.reasons)


def test_explicit_generator_on_human_wording_stays_bounded():
    gen = b.analyze_uploaded_bytes("c.docx", _with_core(_docx([HUMAN_PARA] * 12), "python-docx", "2013-12-23T23:15:00Z", "generated by python-docx"))
    # neutral wording: only the first-hand half of the trace counts, never the part that needs agreement
    assert _gen(gen) <= b.META_GEN_MAX + (b.EXPLICIT_GEN_FLOOR + 1e-9) * (1.8 * 0.9 - b.META_GEN_MAX)
    assert gen.score < 35


def test_weak_traces_without_a_named_generator_stay_bounded():
    # one saved session, no edit time: what any single Word paste looks like. Not a generator name, so never lifted.
    r = b.analyze_uploaded_bytes("d.docx", _with_core(_docx([LLM_PARA] * 30)))
    assert _gen(r) <= b.META_GEN_MAX + 1e-9
    assert b.explicit_generator({"creator": "Pandoc", "created": "2024-01-01"}) == 0.0
    assert b.explicit_generator({"creator": "python-docx"}) > 0


def test_statistics_and_subscripts_are_not_typing_slips():
    stats = ["The effect was strong (r = .34, p &lt; .001, n = 106) and stable across the three sites we visited over two years of work."] * 6
    sub = ["Residual need {h,c} is computed from the eligible need {h,c} minus confirmed assistance {h,c} for each household case."] * 4
    r = b.analyze_uploaded_bytes("e.docx", _docx([HUMAN_PARA] * 10 + stats + sub))
    kinds = r.count_by_kind()
    assert not any(f.kind in ("space_before_punct", "no_space_after_punct") for f in r.findings)
    assert getattr(r, "notation_removed", 0) >= 6
    # a real slip is still a slip
    r2 = b.analyze_uploaded_bytes("f.docx", _docx([HUMAN_PARA] * 10 + ["This sentence has a stray space before the full stop ."] * 3))
    assert any(f.kind == "space_before_punct" for f in r2.findings)
    assert kinds is not None


def test_uploads_are_recognised_by_their_bytes():
    docx = _docx([HUMAN_PARA] * 3)
    n = b.normalize_upload_name
    assert n("report", "application/octet-stream", docx) == "report.docx"
    assert n("report.docx.bin", "", docx).endswith(".docx")
    assert n("report.docx (1)", "", docx).endswith(".docx")
    assert n("file", "", b"%PDF-1.7\n1 0 obj") == "file.pdf"
    assert n("notes", "application/octet-stream", "plain text of a note\n".encode()) == "notes.txt"
    assert n("photo.jpg", "image/jpeg", b"\xff\xd8\xff\xe0\x00\x10JFIF" + bytes(range(200))) == "photo.jpg"
    assert n("REPORT.DOCX", "", docx) == "REPORT.docx"
    assert n("", "", b"") == "upload"
    assert n("x.txt", "", docx) == "x.docx"               # the bytes win over a wrong extension
    assert n("old.doc", "application/msword", bytes.fromhex("D0CF11E0A1B11AE1") + b"\0" * 64).endswith(".doc")
