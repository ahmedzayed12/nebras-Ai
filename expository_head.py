DERIVED_INPUTS = ("unit_mean_x", "unit_max_x", "unit_frac_x_gt1", "local_logit", "global_z")
INPUTS = ENGINE_INPUTS + DERIVED_INPUTS
# One logit of excess over the gate closes ~63% of the head's share of the
# remaining distance; the share is capped below 1 so the lifted index stays
# strictly increasing in the underlying evidence (typing errors still count).
LIFT_SCALE = 1.0
LIFT_SHARE = 0.8
# Lifts below this are rounding noise and are not reported as a reason.
MIN_REPORTED_LIFT = 0.05

