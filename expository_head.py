def inputs(feature_rows, units, local_score, global_logit, confidence):
    """feature_rows: {name: (value, weight, contribution)} as in Result.features.

    A feature enters by its EFFECTIVE value contribution / weight, so evidence a
    neutralizer cancelled (contribution zeroed, value kept) never reaches the
    head. The global logit is shrunk by the same length confidence as the
    published global reading.
    """
    words = sum(w for w, _ in units) or 1
    xs = [x for _, x in units] or [0.0]
    local = min(max(local_score, 0.5), 99.5) / 100.0
    derived = (sum(w * x for w, x in units) / words, max(xs), sum(x > 1.0 for x in xs) / len(xs),
               math.log(local / (1.0 - local)), global_logit * confidence)
    values = []
    for k in ENGINE_INPUTS:
        _, weight, contribution = feature_rows.get(k, (0.0, 0.0, 0.0))
        values.append(contribution / weight if weight else 0.0)
    return values + list(derived)


def decision(x, confidence, params=None):
    """Head logit, shrunk by length confidence like the engine's own logit, so
    short texts with noisy uniformity features cannot cross the gate easily."""
    p = params or PARAMS
    raw = p["intercept"] + sum(c * (v - m) / s for v, m, s, c in zip(x, p["mean"], p["scale"], p["coef"]))
    return raw * confidence


def lift(score, d, params=None):
    """Raise score toward 100 by the head's excess over the human gate; never lower it."""
    excess = d - (params or PARAMS)["gate"]
    if excess <= 0:
        return score
    return score + (100.0 - score) * LIFT_SHARE * (1.0 - math.exp(-excess / LIFT_SCALE))
