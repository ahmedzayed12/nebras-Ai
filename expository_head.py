"""v3.2 expository head: a learned read of the SAME v3.1 evidence, upward only.

WHY
  Short generated expository essays (a 300-600 word "research paper" on a
  historical or scientific topic) carry many concrete names and dates, so the
  hand-set global pool and the paragraph reader each see only weak evidence and
  their mean stays low (see benchmarks/v3.2-expository-head.json).

WHAT
  A class-balanced logistic head over the v3.1 text-evidence vector (feature
  values, paragraph wording scores, local and global readings). Each
  coefficient keeps the sign of the engine's own prior for that feature. The
  head can only raise the index, and only when its decision value exceeds the
  highest value seen on any training human document (the gate).

DATA
  Trained only on external manifests (tools/train_expository_head.py): pre-2020
  human prose and assistant-generated essays, split by source group, plus the
  100 development PEPs. No submitted user document, target score, reserved
  validation set or synthetic control is used. See benchmarks/README.md.
"""
import math

