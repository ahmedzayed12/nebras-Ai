# -*- coding: utf-8 -*-
"""Word route must not read equations / code / author block / table cells as 'human manual formatting'."""
import io, sys, zipfile, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import backend_adapter as ba
import docx_clean as dc


def P(text, font="Times New Roman", size=10.0, **kw):
    eng = ba.get_engine()
    return eng.Para(text=text, runs=[(0, len(text), font, size, False, False)], **kw)


def test_equation_code_front_and_cells_removed_prose_kept():
    prose = "The proposed method evaluates boundary uncertainty under realistic acquisition conditions and reports stability."
    paras = [P("Jane Doe, Department of Mathematics, University X; jane@x.edu", size=8, align="center"),
             P("Abstract"),
             P(prose), P("x = y + 1   (1)", font="Cambria Math", align="center"),
             P("def f(x):\n return x", font="Consolas", hard_breaks=3),
             P("0.91", in_table=True), P(prose)]
    out, st = dc.clean_docx_paras(paras)
    texts = [p.text for p in out]
    assert prose in texts and not any("Cambria" in str(p.runs) or "def f" in p.text or p.text == "0.91" for p in out)
    assert st.equations == 1 and st.code == 1 and st.table_cells == 1 and st.front == 1


def test_generator_declared_in_description_is_found():
    b = io.BytesIO()
    with zipfile.ZipFile(b, "w") as z:
        z.writestr("docProps/core.xml", "<cp:coreProperties xmlns:dc='x'><dc:description>generated by python-docx</dc:description></cp:coreProperties>")
    assert dc.generator_from_description(b.getvalue()) == "generated by python-docx"


def test_phone_uploads_regain_their_extension():
    n = ba.normalize_upload_name
    assert n("REPORT.DOCX") == "REPORT.docx"
    assert n("document", "application/pdf") == "document.pdf"
    assert n("اسم", "application/vnd.openxmlformats-officedocument.wordprocessingml.document") == "اسم.docx"
    assert n("photo.jpg", "image/jpeg") == "photo.jpg"       # unsupported stays unsupported (clear error later)
